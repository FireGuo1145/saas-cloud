import type {
  Database,
  FieldDefinition,
  FieldType,
  IndexDefinition,
  Query,
  Schema,
  Tables,
  UpdateData,
} from "@yumerijs/types";

export type { Database, FieldDefinition, FieldType, IndexDefinition, Query, Schema, Tables, UpdateData };

export interface SqlDriver {
  dialect: "sqlite" | "mysql" | "pgsql";
  execute(sql: string, params?: unknown[]): Promise<{ changes?: number; insertId?: number | bigint }>;
  one(sql: string, params?: unknown[]): Promise<Record<string, unknown> | undefined>;
  many(sql: string, params?: unknown[]): Promise<Record<string, unknown>[]>;
  close(): Promise<void>;
}

function identifier(value: string) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(value)) throw new Error(`Invalid SQL identifier: ${value}`);
  return `"${value}"`;
}

function fieldType(type: FieldType) {
  const types: Record<FieldType, string> = {
    string: "TEXT",
    text: "TEXT",
    json: "TEXT",
    integer: "INTEGER",
    unsigned: "INTEGER",
    bigint: "BIGINT",
    float: "REAL",
    double: "DOUBLE PRECISION",
    decimal: "DECIMAL",
    boolean: "BOOLEAN",
    date: "DATETIME",
    time: "TIME",
    timestamp: "DATETIME",
  };
  return types[type];
}

function definitionOf(value: string | FieldDefinition): FieldDefinition {
  return typeof value === "string" ? { type: value as FieldType } : value;
}

function defaultSql(value: unknown) {
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value === null) return "NULL";
  return String(value);
}

function where(query: Query<any>, params: unknown[], strict = false): string {
  const parts: string[] = [];
  for (const [key, value] of Object.entries(query)) {
    if (key === "$or" || key === "$and") {
      const items = (value as Query<any>[]).map((item) => where(item, params, strict)).filter(Boolean);
      if (items.length) parts.push(`(${items.join(key === "$or" ? " OR " : " AND ")})`);
      continue;
    }
    const column = identifier(key);
    if (value === undefined) {
      if (strict) throw new Error(`Refusing query with undefined filter "${key}"`);
      continue;
    }
    if (value === null) {
      parts.push(`${column} IS NULL`);
      continue;
    }
    if (typeof value === "object" && !Array.isArray(value) && !(value instanceof Date)) {
      for (const [operator, operand] of Object.entries(value as Record<string, unknown>)) {
        if (operand === undefined || operand === null) continue;
        if (operator === "$in" || operator === "$nin") {
          const values = operand as unknown[];
          if (!values.length) {
            parts.push(operator === "$in" ? "1 = 0" : "1 = 1");
            continue;
          }
          parts.push(`${column} ${operator === "$in" ? "IN" : "NOT IN"} (${values.map(() => "?").join(", ")})`);
          params.push(...values);
          continue;
        }
        const symbols: Record<string, string> = { $eq: "=", $ne: "!=", $gt: ">", $gte: ">=", $lt: "<", $lte: "<=" };
        const symbol = symbols[operator];
        if (symbol) {
          parts.push(`${column} ${symbol} ?`);
          params.push(operand);
        }
      }
      continue;
    }
    parts.push(`${column} = ?`);
    params.push(value);
  }
  return parts.join(" AND ");
}

/** SQL implementation of Yumeri's database contract shared by database drivers. */
export class SqlDatabase implements Database {
  constructor(private readonly driver: SqlDriver) {}

  async extend<K extends keyof Tables>(table: K, schema: Schema<Partial<Tables[K]>>, indexes?: IndexDefinition<Tables[K]>): Promise<void> {
    const tableName = identifier(String(table));
    const columns = Object.entries(schema).map(([name, input]) => {
      const definition = definitionOf(input as string | FieldDefinition);
      let sql = `${identifier(name)} ${fieldType(definition.type)}`;
      if (definition.nullable === false) sql += " NOT NULL";
      if (definition.autoIncrement) {
        sql += this.driver.dialect === "pgsql"
          ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
          : this.driver.dialect === "mysql"
            ? " AUTO_INCREMENT PRIMARY KEY"
            : " PRIMARY KEY AUTOINCREMENT";
      }
      if (definition.initial !== undefined) sql += ` DEFAULT ${defaultSql(definition.initial)}`;
      return sql;
    });
    if (!columns.length) throw new Error(`Cannot create table ${String(table)} without columns`);
    await this.driver.execute(`CREATE TABLE IF NOT EXISTS ${tableName} (${columns.join(", ")})`);

    for (const [name, input] of Object.entries(schema)) {
      if (name === "id") continue;
      const definition = definitionOf(input as string | FieldDefinition);
      let column = `${identifier(name)} ${fieldType(definition.type)}`;
      if (definition.initial !== undefined) column += ` DEFAULT ${defaultSql(definition.initial)}`;
      try {
        await this.driver.execute(`ALTER TABLE ${tableName} ADD COLUMN ${column}`);
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        if (!/duplicate column|already exists/i.test(message)) throw error;
      }
    }

    for (const key of indexes?.unique ?? []) {
      const fields = (Array.isArray(key) ? key : [key]).map((field) => identifier(String(field))).join(", ");
      const name = `${String(table)}_${Array.isArray(key) ? key.join("_") : String(key)}_unique`;
      await this.driver.execute(`CREATE UNIQUE INDEX IF NOT EXISTS ${identifier(name)} ON ${tableName} (${fields})`);
    }
  }

  async create<K extends keyof Tables>(table: K, data: Partial<Tables[K]>): Promise<Tables[K]> {
    const entries = Object.entries(data);
    if (!entries.length) throw new Error(`Cannot insert an empty row into ${String(table)}`);
    const result = await this.driver.execute(
      `INSERT INTO ${identifier(String(table))} (${entries.map(([key]) => identifier(key)).join(", ")}) VALUES (${entries.map(() => "?").join(", ")})`,
      entries.map(([, value]) => value),
    );
    const explicitId = (data as Record<string, unknown>).id;
    if (explicitId !== undefined && explicitId !== null) return { ...data } as Tables[K];
    return { ...data, ...(result.insertId === undefined ? {} : { id: Number(result.insertId) }) } as Tables[K];
  }

  async select<K extends keyof Tables, F extends keyof Tables[K]>(table: K, query: Query<Tables[K]>, fields?: F[]): Promise<Pick<Tables[K], F>[]> {
    const params: unknown[] = [];
    const condition = where(query, params);
    const selected = fields?.length ? fields.map((field) => identifier(String(field))).join(", ") : "*";
    return await this.driver.many(`SELECT ${selected} FROM ${identifier(String(table))}${condition ? ` WHERE ${condition}` : ""}`, params) as Pick<Tables[K], F>[];
  }

  async selectOne<K extends keyof Tables, F extends keyof Tables[K]>(table: K, query: Query<Tables[K]>, fields?: F[]): Promise<Pick<Tables[K], F> | undefined> {
    return (await this.select(table, query, fields))[0];
  }

  async update<K extends keyof Tables>(table: K, query: Query<Tables[K]>, data: UpdateData<Partial<Tables[K]>>): Promise<number> {
    const params: unknown[] = [];
    const assignments = Object.entries(data).map(([key, value]) => {
      const column = identifier(key);
      if (value && typeof value === "object" && "$inc" in value) {
        params.push((value as { $inc: number }).$inc);
        return `${column} = ${column} + ?`;
      }
      params.push(value);
      return `${column} = ?`;
    });
    if (!assignments.length) throw new Error(`Refusing to update ${String(table)} without values`);
    const condition = where(query, params, true);
    if (!condition) throw new Error(`Refusing to update ${String(table)} without a filter`);
    const result = await this.driver.execute(`UPDATE ${identifier(String(table))} SET ${assignments.join(", ")} WHERE ${condition}`, params);
    return result.changes ?? 0;
  }

  async remove<K extends keyof Tables>(table: K, query: Query<Tables[K]>): Promise<number> {
    const params: unknown[] = [];
    const condition = where(query, params, true);
    if (!condition) throw new Error(`Refusing to delete from ${String(table)} without a filter`);
    const result = await this.driver.execute(`DELETE FROM ${identifier(String(table))} WHERE ${condition}`, params);
    return result.changes ?? 0;
  }

  async upsert<K extends keyof Tables>(table: K, data: Partial<Tables[K]>[], key: keyof Tables[K] | (keyof Tables[K])[], update?: UpdateData<Partial<Tables[K]>>): Promise<void> {
    const fields = Array.isArray(key) ? key : [key];
    for (const row of data) {
      const query = Object.fromEntries(fields.map((field) => [field, row[field]])) as Query<Tables[K]>;
      if (await this.selectOne(table, query)) await this.update(table, query, update ?? row);
      else await this.create(table, row);
    }
  }

  async drop<K extends keyof Tables>(table: K): Promise<void> {
    await this.driver.execute(`DROP TABLE IF EXISTS ${identifier(String(table))}`);
  }

  run(sql: string, params?: unknown[]) { return this.driver.execute(sql, params); }
  get(sql: string, params?: unknown[]) { return this.driver.one(sql, params); }
  all(sql: string, params?: unknown[]) { return this.driver.many(sql, params); }
  close() { return this.driver.close(); }
}
